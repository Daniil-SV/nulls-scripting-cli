import { confirm, isCancel, log, select } from "@clack/prompts";
import Api, {
	ScriptingAPIError,
	type ScriptSummary,
} from "@/api/scripting/index.js";
import config from "@/config.js";
import { readScriptContent } from "@/shared/content.js";
import {
	applyMetadata,
	metadataFromConfig,
	type ScriptMetadata,
	validateMetadata,
} from "@/shared/metadata.js";
import { isUuid } from "@/shared/uuid.js";

export enum ScriptFiltering {
	None,
	Author,
}

export async function findScript(
	name: string,
	filtering: ScriptFiltering = ScriptFiltering.None,
	silent: boolean = false,
): Promise<ScriptSummary | undefined> {
	let scripts: ScriptSummary[];
	if (filtering === ScriptFiltering.Author) {
		const response = await Api.get("/users/{userId}/scripts", {
			params: { path: { userId: Api.user.uuid } },
		});
		scripts = response.scripts;
	} else {
		const response = await Api.get("/scripts");
		scripts = response.scripts;
	}

	const filtered = scripts.filter((summary) => {
		return summary.name.includes(name);
	});

	if (filtered.length === 0) return undefined;
	if (filtered.length === 1 || silent) return filtered[0];
	if (filtered.length > 10) {
		throw new Error("Too many scripts found! Try to clarify your request");
	}

	const selected = (await select({
		message: "Found multiple scripts. Please select one",
		options: filtered.map((summary) => {
			return {
				value: summary.script_id,
				label: summary.name,
				hint: summary.author_name,
			};
		}),
	})) as string;

	if (isCancel(selected)) {
		return filtered[0];
	}

	return filtered.find((summary) => summary.script_id === selected);
}

/**
 * Creates a draft script owned by the current user and applies its metadata.
 * The script is always created in the API: its id is generated by the server.
 */
export async function createScript(
	metadata: ScriptMetadata & { name: string },
	content = "",
): Promise<string> {
	validateMetadata(metadata);

	const { script_id } = await Api.post("/scripts", {
		body: { name: metadata.name, content },
	});

	await applyMetadata(script_id, metadata);

	return script_id;
}

/**
 * Handles a script that cannot be modified.
 * A foreign script is offered for forking into a new owned script.
 * When `requested` is omitted the script does not exist, so the user is
 * offered to create a new one.
 */
async function adoptScript(
	requested?: string,
	target?: ScriptSummary,
): Promise<ScriptSummary> {
	const metadata = metadataFromConfig(config);
	const name = metadata.name ?? target?.name;

	if (name === undefined) {
		throw new Error("Failed to resolve script name");
	}

	// A fresh script has no description, so only a real value is applied
	const patch: ScriptMetadata & { name: string } = { name };
	if (metadata.description !== undefined && metadata.description !== null) {
		patch.description = metadata.description;
	}

	validateMetadata(patch);

	if (requested === undefined) {
		log.warn("The target script does not exist.");
	} else {
		const label =
			target === undefined
				? `script ${requested}`
				: `"${target.name}" by ${target.author_name}`;

		log.warn(`You are not the author of ${label}, so it cannot be modified.`);
	}

	const accepted = await confirm({
		message:
			"Create a new script under your account and switch the config to it?",
		initialValue: true,
	});

	if (isCancel(accepted) || accepted !== true) {
		throw new Error(
			requested === undefined
				? "Script not found"
				: target === undefined
					? `You do not have access to script by UUID ${requested}`
					: "You don't have access to this script!",
		);
	}

	const content =
		config.path === undefined ? undefined : readScriptContent(config.path);

	const script_id = await createScript(patch, content);

	if (config.path === undefined) {
		log.warn("The config has no `path`, so the new script is left empty.");
	}

	await config.patch({ id: script_id });

	return {
		script_id,
		name,
		description: patch.description ?? null,
		created_at: new Date().toISOString(),
		updated_at: new Date().toISOString(),
		published_at: null,
		author_uuid: Api.user.uuid,
		author_name: Api.user.name,
		is_favorite: false,
	};
}

/**
 * Verifies write access to the script and returns the id to use
 * A foreign script may be forked into a new script owned by the user
 */
export async function ensureWriteAccess(id: string): Promise<string> {
	if (!isUuid(id)) return id;

	const target = await resolveScript(id, "r");

	// Target doesn't exist, propose to create a new one
	if (target === undefined) {
		const { script_id } = await adoptScript();
		return script_id;
	}

	// Target confirmed, everything is okay
	if (target.author_uuid === Api.user.uuid) {
		return id;
	}

	// Script exists but user doesn't own it
	// Propose to fork script and change config
	const { script_id } = await adoptScript(id, target);
	return script_id;
}

export async function resolveScript(
	id: string,
	mode: "rw" | "r" | "w",
): Promise<ScriptSummary | undefined> {
	const writeAccess = mode.includes("w");
	const readAccess = mode.includes("r");

	let target: ScriptSummary | undefined;
	if (isUuid(id)) {
		try {
			target = await Api.get("/scripts/{scriptId}", {
				params: { path: { scriptId: id } },
			});
		} catch (error) {
			if (error instanceof ScriptingAPIError && error.status === 404) {
				// A missing script, not a draft: own drafts are returned to their author
				return undefined;
			}

			throw error;
		}

		if (writeAccess && target !== undefined) {
			if (target.author_uuid !== Api.user.uuid) {
				return await adoptScript(id, target);
			}
		}

		return target;
	}

	// Search only for author scripts if request write
	// Only author of scripts could write to scripts
	target = await findScript(
		id,
		readAccess ? ScriptFiltering.None : ScriptFiltering.Author,
		true,
	);

	return target;
}

export async function resolveScriptIdOrCreate(
	id: string,
	content?: string,
): Promise<ScriptSummary> {
	const target = await resolveScript(id, "w");

	if (target !== undefined) {
		return target;
	}

	if (isUuid(id)) {
		return await adoptScript();
	}

	const script_id = await createScript({ name: id }, content);

	return {
		script_id,
		name: id,
		description: null,
		created_at: new Date().toISOString(),
		updated_at: new Date().toISOString(),
		published_at: null,
		author_uuid: Api.user.uuid,
		author_name: Api.user.name,
		is_favorite: false,
	};
}
