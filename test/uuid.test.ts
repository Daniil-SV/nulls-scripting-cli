import { describe, expect, it } from "vitest";
import { isUuid } from "@/shared/uuid.js";

describe("isUuid", () => {
	it("accepts a UUIDv4", () => {
		expect(isUuid("11111111-1111-4111-8111-111111111111")).toBe(true);
	});

	it("accepts a UUIDv7 generated by the API", () => {
		expect(isUuid("01a1cf19-3378-709c-b4dd-6e03f561dc93")).toBe(true);
	});

	it("rejects names and malformed ids", () => {
		expect(isUuid("my script")).toBe(false);
		expect(isUuid("01a1cf19-3378-709c-b4dd-6e03f561dc9")).toBe(false);
		expect(isUuid("01a1cf19-3378-709c-b4dd-6e03f561dc93-extra")).toBe(false);
	});
});
